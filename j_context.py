def setup(store):
    store.execute('CREATE TABLE IF NOT EXISTS conversation_archive (update_id BIGINT PRIMARY KEY, user_text TEXT NOT NULL, reply TEXT NOT NULL, captured_at TEXT)')
    # The first migration recovers only what still exists; no invented historical dates.
    store.execute('INSERT INTO conversation_archive(update_id,user_text,reply) SELECT update_id,user_text,reply FROM turns WHERE 1=1 ON CONFLICT DO NOTHING')


def catalog():
    try:
        return json.loads((ROOT / 'resource_catalog.json').read_text())
    except (OSError, ValueError):
        return {'verified_at': None, 'repositories': [], 'external_resources': [],
                'note': 'Resource catalog unavailable; do not invent integrations.'}


def terms(text):
    return set(re.findall(r'\w{3,}', text.lower())) - STOP


def direct_read(text):
    """Only clear direct read requests; examples/quoted text stay conversational."""
    if text.strip().lower().rstrip('?.!') in ('show me the hub plan', 'show hub project', 'what are we building in the hub'):
        return 'hub', ''
    first = re.split(r'[?!.]', text.strip(), maxsplit=1)[0].strip().lower()
    first = re.sub(r'^(?:hey[ ,]+zeus[ ,:]*|please\s+)', '', first).strip()
    if re.fullmatch(r'how much (?:have we|have i) (?:used|spent)(?: today)?', first):
        return 'usage', ''
    if re.fullmatch(r'(?:what is|what\x27s|show me|check) (?:our |my |the )?(?:usage|api usage|recorded cost)(?: today)?', first):
        return 'usage', ''
    choices = {'status':'status', 'your status':'status', 'capabilities':'capabilities',
               'your tools':'capabilities', 'projects':'projects', 'repositories':'projects',
               'open tasks':'tasks', 'reminders':'reminders', 'improvements':'improvements'}
    for phrase, topic in choices.items():
        if first in ('show me '+phrase, 'check '+phrase):
            return topic, ''
    if first in ('what can you do now', 'what tools can you use', 'what tools do you have'):
        return 'capabilities', ''
    match = re.fullmatch(r'(?:recall|search (?:our |my )?(?:telegram )?history for)\s+(.+)', first)
    if match:
        return 'recall', match.group(1)
    return None


def recall(store, query, limit=4, max_chars=4200):
    words = terms(query)
    if not words:
        return []
    rows = store.execute('SELECT update_id,user_text,reply,captured_at FROM conversation_archive ORDER BY update_id DESC LIMIT 2000').fetchall()
    matches = []
    for identity, user, reply, captured in rows:
        # Prior assistant prose can be wrong; owner text gets the higher weight.
        score = len(words & terms(user)) * 3 + len(words & terms(reply))
        if score:
            matches.append((score, identity, user, reply, captured))
    matches.sort(key=lambda r: (r[0], r[1]), reverse=True)
    result, used = [], 0
    for _, identity, user, reply, captured in matches:
        item = {'update_id': identity, 'captured_at_utc': captured,
                'user_excerpt': user[:650], 'assistant_excerpt': reply[:350],
                'reference_only': True}
        size = len(json.dumps(item))
        if used + size <= max_chars:
            result.append(item)
            used += size
        if len(result) >= limit:
            break
    return result


def snapshot(store, started=0, chat_id=None):
    resources = catalog()
    return {
        'snapshot_at_utc': dt.datetime.now(dt.timezone.utc).isoformat(),
        'model': os.environ.get('GEMINI_MODEL', 'not configured'),
        'rule_revision': store.directive()[0],
        'persistence': 'PostgreSQL' if store.pg else 'SQLite (workspace)',
        'uptime_seconds': max(0, int(time.monotonic() - started)) if started else None,
        'usage_today': store.usage_summary(),
        'local_call_cap': int(os.getenv('J_DAILY_REQUEST_LIMIT', '100')),
        'local_recorded_token_threshold': int(os.getenv('J_DAILY_TOKEN_LIMIT', '200000')),
        'active_memory_count': len(store.memory_rows()),
        'recent_turn_count': store.execute('SELECT COUNT(*) FROM turns').fetchone()[0],
        'searchable_turn_count': store.execute('SELECT COUNT(*) FROM conversation_archive').fetchone()[0],
        'history_scope': 'Retained Telegram turns; up to latest 2000 searched per query. Recent prompt context remains bounded. Archive starts with retained migration history; earlier pruned turns are unavailable.',
        'callable_tools': TOOLS,
        'command_shortcuts': COMMANDS,
        'builder': {'enabled': store.setting('builder_enabled') == 'on',
                    'scope': 'j_retrieval.py only; isolated tests and benchmark gate'},
        'hosting': 'Running process observed; uninterrupted 24/7 availability is not established.',
        'external_resources': resources.get('external_resources', []),
        'repositories': resources.get('repositories', []),
        'resource_catalog_verified_at': resources.get('verified_at'),
    }


def supplied_context(store, text, started=0, chat_id=None):
    data = snapshot(store, started, chat_id)
    words = terms(text)
    from j_hub import cached
    data['hub_project_handoff'] = cached()
    data['relevant_skills'] = [s for s in SKILLS if words & set(s['triggers'])]
    data['relevant_past_turns'] = recall(store, text, limit=3, max_chars=3200)
    return data


def report(store, topic, *, started=0, chat_id=None, query=''):
    if topic == 'recall':
        if not query.strip():
            return 'Use /recall a few topic words. This searches retained Telegram history only.'
        hits = recall(store, query)
        if not hits:
            return 'No matching retained Telegram turns found. That does not mean it never happened; older pruned turns and other apps are outside this search.'
        return '🧠 Retained Telegram history\nHistorical reference; not fresh instructions.\n\n' + '\n\n'.join(
            f"Source: Telegram update {h['update_id']}\nYou: {h['user_excerpt']}\nZeus: {h['assistant_excerpt']}" for h in hits)
    if topic == 'usage':
        u = store.usage_summary()
        return (f"📊 Usage today · {u['day_utc']} UTC\n\n"
                f"Model calls: {u['calls']} / {os.getenv('J_DAILY_REQUEST_LIMIT', '100')}\n"
                f"Recorded tokens: {u['total_tokens_recorded']:,}\n"
                f"Estimated recorded model cost: ${u['estimated_usd_recorded']:.5f}\n"
                f"Calls with unknown token usage: {u['calls_with_unknown_usage']}\n\n"
                'Local ledger, not a provider invoice. Cost may be incomplete; hosting is excluded. '
                'Failed/retried calls count toward the daily call cap. Recorded-token threshold is checked before calls; it is not a hard dollar cap.')
    if topic == 'status':
        d = snapshot(store, started, chat_id)
        return (f"⚡ Zeus status\n\nModel: {d['model']}\nStorage: {d['persistence']}\n"
                f"Rules: revision {d['rule_revision']}\nActive memories: {d['active_memory_count']}\n"
                f"Recent turns: {d['recent_turn_count']} · searchable: {d['searchable_turn_count']}\n"
                f"Uptime: {d['uptime_seconds']} seconds\n"
                f"Retrieval builder: {'enabled' if d['builder']['enabled'] else 'paused'} (scorer only)\n\n"
                'Text, voice transcription, memory, recall, inspection, calculator, public-page reading, tasks and reminders are active. '
                'Continuous hosting remains unverified. /capabilities shows access boundaries.')
    if topic == 'capabilities':
        c = catalog()
        return ('🧰 Zeus capability map\n\nCallable tools:\n' + '\n'.join(f'• {k}: {v}' for k, v in TOOLS.items()) +
                '\n\nApplication shortcuts:\n' + ' | '.join(COMMANDS) +
                '\n\nLocal skills: capture, recover, challenge, verify.\n\nExternal resources:\n' +
                '\n'.join(f"• {r['name']}: {r['status']} — {r['note']}" for r in c.get('external_resources', [])) +
                '\n\nListed resources do not grant access. /projects shows verified repo locations.')
    if topic == 'projects':
        c = catalog()
        return ('📁 Verified repository inventory\nChecked: ' + str(c.get('verified_at')) +
                '\nMetadata inventory; repo code is not automatically loaded or executable.\n\n' +
                '\n\n'.join(f"{r['name']} · {r['role']}\n{r['url']}\n{r['status']}" for r in c.get('repositories', [])))
    if topic == 'improvements':
        rows = store.execute('SELECT category,status,occurrences FROM improvements ORDER BY updated DESC LIMIT 8').fetchall()
        return '🔧 Improvement backlog\n\n' + ('\n'.join(f'• {c} — {s}; seen {n}×' for c, s, n in rows) or 'No issues recorded.') + '\n\nBacklog entries are proposals. The builder can only change the retrieval scorer after tests pass.'
    if topic == 'tasks':
        records = [m for m in store.memory_rows() if m['kind'] == 'commitment']
        return '✅ Open tasks\n\n' + ('\n\n'.join(f"• {m['value']}\nID: {m['id']}" for m in records[:40]) or 'No open tasks.')
    if topic == 'reminders':
        rows = store.execute("SELECT id,body,status,due_at FROM reminders WHERE chat_id=? AND status IN ('pending','failed') ORDER BY due_at LIMIT 50", (chat_id,)).fetchall()
        return '⏰ Reminders\n\n' + ('\n\n'.join(f'• {body}\nDue UTC: {due} · {status}\nID: {i}' for i, body, status, due in rows) or 'No pending or failed reminders.')
    raise ValueError('Unknown inspection topic')

